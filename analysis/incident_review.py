"""Incident write-up, regenerated from ClickHouse on every build.

Usage: python analysis/incident_review.py --out analysis/incident_review.md
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from pipeline.ch import client  # noqa: E402


def pct(x):
    return "n/a" if x is None else f"{100 * x:.1f}%"


def build(c) -> str:
    q = lambda s: c.query(s).result_rows
    rb = {(p, b): (n, a, s) for p, b, n, a, s in q("SELECT platform, build, d1_installs, d1_active_rate, d1_session_start_rate FROM game.rpt_retention_build")}
    cf = {(p, b): (s, x, f, nf) for p, b, s, x, f, nf in q("SELECT platform, build, sessions, crashed_sessions, crash_free_sessions, naive_crash_free FROM game.rpt_crash_free")}
    l7 = q("""SELECT platform, build, device_tier, sum(starts), sum(crashes) FROM game.rpt_levels WHERE level = 7
              GROUP BY platform, build, device_tier ORDER BY platform, build, device_tier""")
    checks = {n: (v, d) for n, v, d in q("SELECT check_name, value, detail FROM game.rpt_checks")}
    out = ["# Incident review: did build 3.5.0 hurt retention?\n",
           "Generated by `analysis/incident_review.py` from the ClickHouse gold tables. Synthetic data; demo results.\n",
           "## Symptom\n",
           "After 3.5.0 shipped on 6 October 2026, day-1 retention measured on `session_start` fell on both platforms.\n",
           "| Platform | Build | Installs | D1 on session_start | D1 on any engagement |", "|---|---|---|---|---|"]
    for (p, b), (n, a, s) in sorted(rb.items()):
        out.append(f"| {p} | {b} | {n:,} | {pct(s)} | {pct(a)} |")
    out += ["\n## Instrumentation checks first\n"]
    for name in ("Duplicate deliveries removed", "Events with no build ID", "Out-of-order events", "New event names",
                 "Deliveries past the watermark (incremental run)", "Deferred crash reports", "Crash reports outside the attribution window"):
        v, d = checks[name]
        out.append(f"- **{name}:** {v:,.0f}. {d}.")
    out += ["\nOne finding changes the metric: a new event, `app_resume`, appears only on iOS from 3.5.0, and iOS `session_start` "
            "volume falls at the same time. Resumed sessions used to be logged as `session_start`. Retention defined on "
            "`session_start` therefore drops on iOS without any change in players. Measured on any engagement event, iOS D1 is flat.\n",
            "## The real regression\n",
            "| Platform | Build | Memory tier | Level-7 starts | Crashes | Per start |", "|---|---|---|---|---|---|"]
    for p, b, t, s, x in l7:
        out.append(f"| {p} | {b} | {t} | {s:,} | {x:,} | {pct(x / s if s else None)} |")
    a35, a341 = cf[("android", "3.5.0")], cf[("android", "3.4.1")]
    out += [f"\nOn Android 3.5.0, low-memory devices crash at the start of level 7. Crash-free sessions on Android fell from "
            f"{pct(a341[2])} to {pct(a35[2])}, and Android D1 retention (any engagement) from {pct(rb[('android', '3.4.1')][1])} "
            f"to {pct(rb[('android', '3.5.0')][1])}. Players who crash on their first day return less.\n",
            "## Actions\n",
            "1. Hotfix level-7 asset loading for low-memory Android devices; watch the level-7 crash rate and Android D1 for the hotfix cohort.",
            "2. Redefine the retention dashboard on any engagement event, and register `app_resume` as a known event.",
            "3. Keep the session-based crash-free denominator; the naive ratio on session_start events misreads iOS 3.5.0."]
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="analysis/incident_review.md")
    a = ap.parse_args()
    Path(a.out).write_text(build(client()), encoding="utf-8", newline="\n")
    print("wrote", a.out)


if __name__ == "__main__":
    main()
